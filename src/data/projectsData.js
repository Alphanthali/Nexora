export function getProjectById(id) {
  if (!id) return projectsData[0];
  const normalizedId = id.toString().toLowerCase();
  const found = projectsData.find(
    (p) => p.id === normalizedId || p.id === normalizedId.replace(/[^a-z0-9]/g, '')
  );
  if (found) return found;
  
  // Also match by numeric ID or title prefix
  if (!isNaN(id)) {
    const idx = parseInt(id, 10) - 1;
    if (idx >= 0 && idx < projectsData.length) return projectsData[idx];
  }

  // Fallback to DigiNest if not found
  return projectsData[0];
}
